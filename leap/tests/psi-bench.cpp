/*
 * PSI from the Leap OPRF (two processes / two machines), with a 128-bit OPRF
 * output per element. Same protocol as the Pool and Valkyrie PSI benchmarks:
 *
 *   offline: Leap preprocessing (base OT + OT extension and the derived
 *            correlations) for 2 * |X| OPRF evaluations;
 *   oprf:    one batched Leap online phase (subset-sum, OLE, rounding) on the
 *            inputs H(x, 0), H(x, 1) for every x in X. Leap outputs 64 bits per
 *            evaluation, so F(x) = F_k(H(x, 0)) || F_k(H(x, 1)) is 128 bits;
 *   set:     the server sends F(y) for every y in Y, shuffled, 16 B each; the
 *            client looks them up and learns X ∩ Y.
 *
 * Phase `online` = oprf + set. Each phase starts after a 1-byte barrier (not
 * measured) and prints a RESULT line: wall-clock time, process CPU time and
 * bytes sent/received on the coproto socket (incl. its 8-byte per-message
 * header).
 *
 * The authors' batched OPRF code (SpringNRPSIServer / SpringNRPSIClient) is
 * used unchanged; its cuckoo-filter PSI is bypassed (Setup() is run with a
 * one-element dummy set, not measured) so that all three protocols use the
 * same set-transfer step.
 *
 * Sets are synthetic and generated by both parties from fixed seeds (testing
 * only): the client's first `intersection` elements are spread over the server
 * set, the rest are fresh.
 *
 * Usage:
 *   psi-bench server 0.0.0.0     <port> <client_size> [server_size] [intersection]
 *   psi-bench client <server-ip> <port> <client_size> [server_size] [intersection]
 */
#include <algorithm>
#include <array>
#include <coproto/Socket/AsioSocket.h>
#include <cryptoTools/Crypto/RandomOracle.h>
#include <cstring>
#include <ctime>
#include <iostream>
#include <leap/oprf/PRF.h>
#include <leap/psi/SpringNRPSIClient.h>
#include <leap/psi/SpringNRPSIServer.h>
#include <string>

using Out128 = std::array<uint64_t, 2>;
// Leap evaluations per PSI element (64 output bits each).
static const size_t kEvalsPerElement = 2;

static void barrier(cp::Socket &sock, bool isServer) {
  uint8_t token = 0;
  if (isServer) {
    coproto::sync_wait(sock.recv(token));
    coproto::sync_wait(sock.send(token));
  } else {
    coproto::sync_wait(sock.send(token));
    coproto::sync_wait(sock.recv(token));
  }
  coproto::sync_wait(sock.flush());
}

static double cpu_ms() {
  timespec ts;
  clock_gettime(CLOCK_PROCESS_CPUTIME_ID, &ts);
  return ts.tv_sec * 1e3 + ts.tv_nsec / 1e6;
}

struct Meter {
  cp::Socket &sock;
  std::chrono::steady_clock::time_point wall0;
  double cpu0;
  size_t sent0, recv0;
  explicit Meter(cp::Socket &s)
      : sock(s), wall0(std::chrono::steady_clock::now()), cpu0(cpu_ms()),
        sent0(s.bytesSent()), recv0(s.bytesReceived()) {}
  void report(const char *role, const char *phase, size_t batch) {
    double wall = std::chrono::duration<double, std::milli>(
                      std::chrono::steady_clock::now() - wall0)
                      .count();
    std::cout << "RESULT protocol=leap role=" << role << " phase=" << phase
              << " batch=" << batch << " wall_ms=" << wall
              << " cpu_ms=" << cpu_ms() - cpu0
              << " sent=" << sock.bytesSent() - sent0
              << " recv=" << sock.bytesReceived() - recv0 << std::endl;
  }
};

// The Leap input for evaluation j of PSI element x: H(x, j), 128 bits.
static osuCrypto::block leap_input(const osuCrypto::block &x, uint64_t j) {
  osuCrypto::RandomOracle ro(sizeof(osuCrypto::block));
  ro.Update(x);
  ro.Update(j);
  osuCrypto::block out;
  ro.Final(out);
  return out;
}

static void make_sets(size_t client_size, size_t server_size,
                      size_t intersection,
                      std::vector<osuCrypto::block> &server,
                      std::vector<osuCrypto::block> &client) {
  osuCrypto::PRNG server_prng(osuCrypto::toBlock(0x505349, 1));
  server.resize(server_size);
  server_prng.get(server.data(), server.size());
  osuCrypto::PRNG client_prng(osuCrypto::toBlock(0x505349, 2));
  client.resize(client_size);
  for (size_t i = 0; i < client_size; i++)
    client[i] = i < intersection ? server[i * server_size / intersection]
                                 : client_prng.get<osuCrypto::block>();
}

int main(int argc, char **argv) {
  if (argc < 5) {
    std::cout << "usage: " << argv[0]
              << " {server|client} {ip} {port} {client_size} [server_size]"
                 " [intersection]"
              << std::endl;
    return -1;
  }
  std::string role = argv[1];
  std::string ip = std::string(argv[2]) + ":" + argv[3];
  size_t client_size = std::stoull(argv[4]);
  size_t server_size = argc > 5 ? std::stoull(argv[5]) : client_size;
  size_t intersection =
      argc > 6 ? std::stoull(argv[6]) : std::min(client_size, server_size) / 2;
  if ((role != "server" && role != "client") || client_size == 0 ||
      server_size == 0 || intersection > std::min(client_size, server_size)) {
    std::cout << "bad arguments" << std::endl;
    return -1;
  }
  std::vector<osuCrypto::block> server_set, client_set;
  make_sets(client_size, server_size, intersection, server_set, client_set);
  const block dummy = toBlock((const uint8_t *)"ffffffff88888888");

  if (role == "server") {
    client_set = {};
    cp::AsioSocket sock = coproto::asioConnect(ip, true);
    LEAP::SpringNRPSIServer server(sock, 1);
    // key generation; the PSI filter of this dummy set is not used
    std::vector<block> dummy_set{dummy};
    server.Setup(dummy_set);

    barrier(sock, true);
    {
      Meter m(sock);
      server.Base();
      m.report("server", "offline", client_size);
    }
    barrier(sock, true);
    Meter online(sock);
    {
      Meter m(sock);
      server.Online();
      coproto::sync_wait(sock.flush());
      m.report("server", "oprf", client_size);
    }
    {
      // PRF values of the server set, in the clear, shuffled
      Meter m(sock);
      std::vector<Out128> enc(server_size);
      for (size_t s = 0; s < server_size; s++)
        for (size_t j = 0; j < kEvalsPerElement; j++)
          enc[s][j] = LEAP::prf(leap_input(server_set[s], j), server.keys());
      PRNG prng(sysRandomSeed());
      for (size_t i = enc.size(); i > 1; i--)
        std::swap(enc[i - 1], enc[prng.get<uint64_t>() % i]);
      coproto::sync_wait(sock.send(enc));
      coproto::sync_wait(sock.flush());
      m.report("server", "set", client_size);
    }
    online.report("server", "online", client_size);
    return 0;
  }

  server_set = {};
  cp::AsioSocket sock = coproto::asioConnect(ip, false);
  LEAP::SpringNRPSIClient client(sock);
  client.Setup();

  barrier(sock, false);
  {
    Meter m(sock);
    client.Base(client_size * kEvalsPerElement);
    m.report("client", "offline", client_size);
  }
  barrier(sock, false);
  Meter online(sock);
  std::vector<std::pair<Out128, size_t>> outputs(client_size);
  {
    Meter m(sock);
    std::vector<block> inputs(client_size * kEvalsPerElement);
    for (size_t e = 0; e < client_size; e++)
      for (size_t j = 0; j < kEvalsPerElement; j++)
        inputs[e * kEvalsPerElement + j] = leap_input(client_set[e], j);
    client.Online(inputs);
    for (size_t e = 0; e < client_size; e++)
      outputs[e] = {Out128{client.last_outputs[e * kEvalsPerElement],
                           client.last_outputs[e * kEvalsPerElement + 1]},
                    e};
    m.report("client", "oprf", client_size);
  }
  std::vector<size_t> found;
  {
    Meter m(sock);
    std::sort(outputs.begin(), outputs.end());
    std::vector<Out128> enc(server_size);
    coproto::sync_wait(sock.recv(enc));
    for (const Out128 &v : enc) {
      auto it = std::lower_bound(outputs.begin(), outputs.end(),
                                 std::make_pair(v, size_t(0)));
      if (it != outputs.end() && it->first == v)
        found.push_back(it->second);
    }
    m.report("client", "set", client_size);
  }
  online.report("client", "online", client_size);

  // correctness: exactly the first `intersection` client elements match
  std::sort(found.begin(), found.end());
  bool ok = found.size() == intersection;
  for (size_t i = 0; ok && i < found.size(); i++)
    ok = (found[i] == i);
  std::cout << "PSI protocol=leap client_size=" << client_size
            << " server_size=" << server_size
            << " intersection=" << intersection << " found=" << found.size()
            << " oprf_evaluations=" << client_size * kEvalsPerElement
            << std::endl;
  std::cout << "CORRECTNESS protocol=leap " << (ok ? "OK" : "FAIL")
            << " (intersection " << found.size() << ", expected "
            << intersection << ")" << std::endl;
  return ok ? 0 : 1;
}
